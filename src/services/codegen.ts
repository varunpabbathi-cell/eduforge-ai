import type { ProjectFile, ProjectPlan } from "@/types";

const pascal = (s: string) => s.replace(/[^a-zA-Z0-9]+/g, " ").trim().split(" ").map((w) => w.charAt(0).toUpperCase() + w.slice(1)).join("");

/** Deterministic template code generator used by the demo AI. */
export function buildFiles(plan: ProjectPlan): ProjectFile[] {
  const pages = plan.pages;
  const files: ProjectFile[] = [];

  files.push({
    path: "src/App.tsx",
    content: `import { BrowserRouter, Routes, Route } from "react-router-dom";
import Navbar from "./components/Navbar";
import Footer from "./components/Footer";
${pages.map((p) => `import ${pascal(p.name)} from "./pages/${pascal(p.name)}";`).join("\n")}

// ${plan.name} — generated by EduForge AI
export default function App() {
  return (
    <BrowserRouter>
      <Navbar />
      <main className="min-h-screen">
        <Routes>
${pages.map((p) => `          <Route path="${p.kind === "home" ? "/" : "/" + p.slug}" element={<${pascal(p.name)} />} />`).join("\n")}
        </Routes>
      </main>
      <Footer />
    </BrowserRouter>
  );
}
`,
  });

  files.push({
    path: "src/components/Navbar.tsx",
    content: `import { Link } from "react-router-dom";

const links = [
${pages.map((p) => `  { to: "${p.kind === "home" ? "/" : "/" + p.slug}", label: "${p.name}" },`).join("\n")}
];

export default function Navbar() {
  return (
    <header className="border-b">
      <nav className="mx-auto flex max-w-6xl items-center justify-between p-4">
        <span className="font-bold">${plan.name}</span>
        <ul className="flex gap-6 text-sm">
          {links.map((l) => (
            <li key={l.to}><Link to={l.to}>{l.label}</Link></li>
          ))}
        </ul>
      </nav>
    </header>
  );
}
`,
  });

  files.push({
    path: "src/components/Footer.tsx",
    content: `export default function Footer() {
  return (
    <footer className="border-t p-6 text-center text-sm text-gray-500">
      © {new Date().getFullYear()} ${plan.name}
    </footer>
  );
}
`,
  });

  for (const p of pages) {
    const name = pascal(p.name);
    let body = "";
    if (p.kind === "home")
      body = `    <section className="mx-auto max-w-6xl px-4 py-20">
      <h1 className="text-4xl font-bold">${plan.name}</h1>
      <p className="mt-4 text-lg text-gray-600">${plan.summary}</p>
    </section>`;
    else if (p.kind === "auth")
      body = `    <form className="mx-auto mt-20 max-w-sm space-y-4" onSubmit={(e) => e.preventDefault()}>
      <h1 className="text-2xl font-bold">Sign in</h1>
      <input type="email" placeholder="Email" className="w-full rounded border p-2" required />
      <input type="password" placeholder="Password" className="w-full rounded border p-2" required />
      <button className="w-full rounded bg-black p-2 text-white">Sign in</button>
    </form>`;
    else if (p.kind === "table")
      body = `    <section className="mx-auto max-w-6xl px-4 py-10">
      <h1 className="text-2xl font-bold">${p.name}</h1>
      <table className="mt-6 w-full text-left">
        <thead><tr><th>Name</th><th>Status</th><th>Updated</th></tr></thead>
        <tbody>
          {rows.map((r) => (
            <tr key={r.id}><td>{r.name}</td><td>{r.status}</td><td>{r.updated}</td></tr>
          ))}
        </tbody>
      </table>
    </section>`;
    else if (p.kind === "dashboard")
      body = `    <section className="mx-auto grid max-w-6xl gap-4 px-4 py-10 sm:grid-cols-3">
      {stats.map((s) => (
        <div key={s.label} className="rounded-xl border p-5">
          <p className="text-sm text-gray-500">{s.label}</p>
          <p className="mt-2 text-3xl font-semibold">{s.value}</p>
        </div>
      ))}
    </section>`;
    else if (p.kind === "form")
      body = `    <form className="mx-auto mt-10 max-w-lg space-y-4 px-4" onSubmit={(e) => e.preventDefault()}>
      <h1 className="text-2xl font-bold">${p.name}</h1>
      <input placeholder="Full name" className="w-full rounded border p-2" required />
      <input type="email" placeholder="Email" className="w-full rounded border p-2" required />
      <button className="rounded bg-black px-4 py-2 text-white">Submit</button>
    </form>`;
    else
      body = `    <section className="mx-auto max-w-3xl px-4 py-16">
      <h1 className="text-3xl font-bold">${p.name}</h1>
      <p className="mt-4 text-gray-600">Content for ${p.name.toLowerCase()}.</p>
    </section>`;

    const imports =
      p.kind === "table"
        ? `import { list${p.entity ? pascal(p.entity) : "Items"} } from "../services/api";\n\nconst rows = list${p.entity ? pascal(p.entity) : "Items"}();\n\n`
        : p.kind === "dashboard"
          ? `const stats = [\n  { label: "Total records", value: 0 },\n  { label: "This week", value: 0 },\n  { label: "Pending", value: 0 },\n];\n\n`
          : "";
    files.push({
      path: `src/pages/${name}.tsx`,
      content: `${imports}export default function ${name}() {\n  return (\n${body}\n  );\n}\n`,
    });
  }

  const ents = plan.entities.length ? plan.entities : ["Items"];
  files.push({
    path: "src/services/api.ts",
    content: `// Data access layer. Replace these in-memory arrays with real database queries.
export interface Row { id: string; name: string; status: string; updated: string }

${ents
  .map(
    (e) => `export function list${pascal(e)}(): Row[] {
  return [
    { id: "1", name: "Sample ${e.replace(/s$/, "")} 1", status: "Active", updated: "Today" },
    { id: "2", name: "Sample ${e.replace(/s$/, "")} 2", status: "Pending", updated: "Yesterday" },
  ];
}`,
  )
  .join("\n\n")}
`,
  });

  if (plan.features.includes("Secure authentication"))
    files.push({
      path: "src/hooks/useAuth.ts",
      content: `import { useState } from "react";

// Wire this to your auth provider. Never store passwords in the browser.
export function useAuth() {
  const [user, setUser] = useState<{ email: string } | null>(null);
  return { user, signIn: (email: string) => setUser({ email }), signOut: () => setUser(null) };
}
`,
    });

  files.push({
    path: "src/utils/format.ts",
    content: `export const formatDate = (d: Date | string) =>
  new Intl.DateTimeFormat("en", { dateStyle: "medium" }).format(new Date(d));
`,
  });

  if (plan.entities.length)
    files.push({
      path: "supabase/schema.sql",
      content: `-- ${plan.name} schema\n${plan.entities
        .map(
          (e) => `create table public.${e.toLowerCase()} (
  id uuid primary key default gen_random_uuid(),
  name text not null,
  status text not null default 'active',
  created_at timestamptz not null default now()
);
alter table public.${e.toLowerCase()} enable row level security;`,
        )
        .join("\n\n")}\n`,
    });

  files.push({
    path: "README.md",
    content: `# ${plan.name}\n\n${plan.summary}\n\n## Features\n${plan.features.map((f) => `- ${f}`).join("\n")}\n\n## Getting started\n\n\`\`\`sh\nnpm install\nnpm run dev\n\`\`\`\n\nGenerated with EduForge AI.\n`,
  });

  files.push({
    path: "package.json",
    content: JSON.stringify(
      {
        name: plan.name.toLowerCase().replace(/[^a-z0-9]+/g, "-"),
        private: true,
        scripts: { dev: "vite", build: "vite build" },
        dependencies: { react: "^19.0.0", "react-dom": "^19.0.0", "react-router-dom": "^7.0.0" },
      },
      null,
      2,
    ) + "\n",
  });

  return files;
}
